# ── DATA DIRECTORY ─────────────────────────────────────────────────────────────
BASE_DIR = Path(__file__).parent

# ── DATA LOADING ───────────────────────────────────────────────────────────────
def _load_vuln():
    path = BASE_DIR / "vulnerability_scores.json"
    with open(path) as f:
        data = json.load(f)
    return {
        "by_fips": {d["fips"]: d for d in data["districts"]},
        "by_name": {d["cd_name"].lower(): d for d in data["districts"]},
        "all":     data["districts"],
        "meta":    data["metadata"],
    }

def _load_layer_scores():
    """
    Reads layer_scores_output.js (generated by build_layer_scores.py).
    Parses the JS const and returns a dict keyed by FIPS.
    """
    path = BASE_DIR / "layer_scores_output.js"
    if not path.exists():
        return {}
    raw = path.read_text()
    # Strip the JS wrapper: "const LAYER_SCORES = {...};"
    json_str = raw.replace("const LAYER_SCORES = ", "").rstrip().rstrip(";")
    # JS uses unquoted keys — convert to valid JSON
    import re
    json_str = re.sub(r'(\b[a-zA-Z_][a-zA-Z_0-9]*\b)(?=\s*:)', r'"\1"', json_str)
    # Remove trailing commas before } or ]
    json_str = re.sub(r',\s*([}\]])', r'\1', json_str)
    try:
        return json.loads(json_str)
    except json.JSONDecodeError:
        return {}

def _load_live_data():
    """
    Loads live_data.json produced by fetch_live_data.py.
    Returns {fips: {eviction_filings_12mo, eviction_rate_per_1k,
                    food_complaints_12mo, food_complaint_rate_per_1k,
                    dob_permits_12mo, dob_permit_rate_per_1k}}
    """
    path = BASE_DIR / "data" / "live_data.json"
    if not path.exists():
        return {}
    try:
        raw = json.loads(path.read_text())
        return raw.get("by_district", {})
    except Exception:
        return {}


# Load at startup — all tools read from these in-memory structures
try:
    VULN = _load_vuln()
except FileNotFoundError:
    VULN = {"by_fips": {}, "by_name": {}, "all": [], "meta": {}}

LAYER_SCORES = _load_layer_scores()
LIVE_DATA    = _load_live_data()

# City averages for context (computed once)
def _city_averages():
    avgs = {}
    for key in ("snap_household_pct","child_poverty_pct","rent_burden_pct",
                "unemployment_pct","noncitizen_pct"):
        vals = [d["indicators"].get(key,0) for d in VULN["all"] if d.get("indicators")]
        avgs[key] = round(sum(vals)/len(vals),1) if vals else 0
    return avgs

CITY_AVGS = _city_averages()


# ── HELPERS ────────────────────────────────────────────────────────────────────
def _find_district(query: str):
    """Fuzzy district lookup with full layer enrichment."""
    q = query.lower().strip()
    d = VULN["by_name"].get(q)
    if not d:
        for name, district in VULN["by_name"].items():
            if q in name or name in q:
                d = district
                break
    if not d:
        return None

    fips = d["fips"]
    ls   = LAYER_SCORES.get(fips, {})
    raw  = ls.get("_raw", {})
    food = d["vulnerability_score"]
    h    = ls.get("housing", 50)
    c    = ls.get("cost_of_living", 50)
    he   = ls.get("health", 50)
    ec   = ls.get("economic", 50)
    eq   = round((food + h + c + he + ec) / 5)

    # City rank
    sorted_all = sorted(VULN["all"], key=lambda x: x["vulnerability_score"], reverse=True)
    rank = next((i+1 for i,x in enumerate(sorted_all) if x["fips"] == fips), None)

    # % above/below city average for each indicator
    vs_city = {
        k: round(d["indicators"].get(k, 0) - CITY_AVGS.get(k, 0), 1)
        for k in CITY_AVGS
    }

    return {
        "name":           d["cd_name"],
        "borough":        d["borough"],
        "fips":           fips,
        "city_rank":      rank,
        "risk_tier":      d["risk_tier"],
        "indicators":     d["indicators"],
        "vs_city_avg":    vs_city,
        "layer_scores": {
            "food":           food,
            "housing":        h,
            "cost_of_living": c,
            "health":         he,
            "economic":       ec,
            "equity":         eq,
        },
        "housing_dev": {
            "completions_2020_2024":   raw.get("completions_5yr", 0),
            "completions_per_1k_units": raw.get("completions_per1k", 0),
            "pipeline_filed":          raw.get("pipeline_filed", 0),
            "pipeline_permitted":      raw.get("pipeline_permitted", 0),
            "pipeline_withdrawn":      raw.get("pipeline_withdrawn", 0),
            "pipeline_inactive":       raw.get("pipeline_inactive", 0),
            "pipeline_stall_rate_pct": raw.get("pipeline_stall_rate", 0),
        },
        "raw_indicators": {
            "hpd_violations_per_1k": raw.get("hpd_per_1k"),
            "life_expectancy_yrs":   raw.get("life_exp"),
            "asthma_per_10k":        raw.get("asthma"),
            "median_monthly_rent":   raw.get("rent"),
            "median_income_k":       raw.get("income_k"),
        },
        "live_data": _live_snapshot(fips),
    }


def _live_snapshot(fips: str):
    """Returns live rolling-12mo indicators for a FIPS if available."""
    ld = LIVE_DATA.get(fips)
    if not ld:
        return {"note": "Run fetch_live_data.py to populate live indicators"}
    return {
        "eviction_filings_12mo":        ld.get("eviction_filings_12mo", 0),
        "eviction_rate_per_1k_hh":      ld.get("eviction_rate_per_1k", 0),
        "food_complaints_12mo":         ld.get("food_complaints_12mo", 0),
        "food_complaint_rate_per_1k":   ld.get("food_complaint_rate_per_1k", 0),
        "dob_permits_12mo":             ld.get("dob_permits_12mo", 0),
        "dob_permit_rate_per_1k":       ld.get("dob_permit_rate_per_1k", 0),
    }


def _layer_score(d_fips, layer, ls=None):
    if ls is None:
        ls = LAYER_SCORES.get(d_fips, {})
    d = VULN["by_fips"].get(d_fips, {})
    food = d.get("vulnerability_score", 50)
    h  = ls.get("housing", 50)
    c  = ls.get("cost_of_living", 50)
    he = ls.get("health", 50)
    ec = ls.get("economic", 50)
    eq = round((food + h + c + he + ec) / 5)
    return {"food": food, "housing": h, "cost_of_living": c,
            "health": he, "economic": ec, "equity": eq}.get(layer, food)


