@server.call_tool()
async def call_tool(name: str, arguments: dict):
    result = _dispatch(name, arguments)
    return [types.TextContent(type="text", text=json.dumps(result, indent=2))]


def _dispatch(name: str, args: dict):
    # ── get_district_data ──────────────────────────────────────────────────────
    if name == "get_district_data":
        d = _find_district(args.get("district_name", ""))
        if not d:
            available = sorted(VULN["by_name"].keys())[:15]
            return {"error": f"District '{args['district_name']}' not found",
                    "hint": "Try partial name. Sample names: " + ", ".join(available)}
        return d

    # ── get_top_vulnerable ─────────────────────────────────────────────────────
    elif name == "get_top_vulnerable":
        n       = args.get("n", 5)
        layer   = args.get("layer", "food")
        borough = args.get("borough", "").strip().lower()

        results = []
        for d in VULN["all"]:
            if borough and d["borough"].lower() != borough:
                continue
            fips = d["fips"]
            ls   = LAYER_SCORES.get(fips, {})
            raw  = ls.get("_raw", {})
            score = _layer_score(fips, layer, ls)
            results.append({
                "name":               d["cd_name"],
                "borough":            d["borough"],
                "fips":               fips,
                "risk_tier":          d["risk_tier"],
                "score_on_layer":     score,
                "layer":              layer,
                "food_score":         d["vulnerability_score"],
                "housing_score":      ls.get("housing", 50),
                "health_score":       ls.get("health", 50),
                "economic_score":     ls.get("economic", 50),
                "cost_of_living":     ls.get("cost_of_living", 50),
                "pipeline_stall_pct": raw.get("pipeline_stall_rate"),
                "completions_per_1k": raw.get("completions_per1k"),
            })

        results.sort(key=lambda x: x["score_on_layer"], reverse=True)
        return {
            "layer":    layer,
            "borough":  borough or "all boroughs",
            "top":      results[:n],
            "note":     "score_on_layer: 0=low stress, 100=highest stress"
        }

    # ── compare_districts ──────────────────────────────────────────────────────
    elif name == "compare_districts":
        da = _find_district(args.get("district_a", ""))
        db = _find_district(args.get("district_b", ""))
        if not da:
            return {"error": f"District '{args.get('district_a')}' not found"}
        if not db:
            return {"error": f"District '{args.get('district_b')}' not found"}

        layers = ["food", "housing", "cost_of_living", "health", "economic", "equity"]
        layer_cmp = []
        for layer in layers:
            va = da["layer_scores"][layer]
            vb = db["layer_scores"][layer]
            layer_cmp.append({
                "layer":    layer,
                "a_score":  va,
                "b_score":  vb,
                "worse":    da["name"] if va > vb else (db["name"] if vb > va else "tied"),
                "gap":      abs(va - vb)
            })

        ind_cmp = []
        for key in ("snap_household_pct","child_poverty_pct","rent_burden_pct",
                    "unemployment_pct","noncitizen_pct"):
            va = da["indicators"].get(key, 0)
            vb = db["indicators"].get(key, 0)
            city = CITY_AVGS.get(key, 0)
            ind_cmp.append({
                "indicator":  key,
                "a_value":    va,
                "b_value":    vb,
                "city_avg":   city,
                "worse":      da["name"] if va > vb else (db["name"] if vb > va else "tied"),
                "gap":        round(abs(va - vb), 1)
            })

        overall_worse = (da["name"] if da["layer_scores"]["equity"] > db["layer_scores"]["equity"]
                         else db["name"])
        return {
            "district_a":          {"name": da["name"], "borough": da["borough"],
                                    "equity_score": da["layer_scores"]["equity"]},
            "district_b":          {"name": db["name"], "borough": db["borough"],
                                    "equity_score": db["layer_scores"]["equity"]},
            "higher_overall_need": overall_worse,
            "layer_comparison":    layer_cmp,
            "indicator_comparison": ind_cmp,
        }

    # ── get_borough_summary ────────────────────────────────────────────────────
    elif name == "get_borough_summary":
        borough = args.get("borough", "").strip()
        districts = [d for d in VULN["all"]
                     if d["borough"].lower() == borough.lower()]
        if not districts:
            return {"error": f"Borough '{borough}' not found. "
                    "Options: Bronx, Brooklyn, Manhattan, Queens, Staten Island"}

        layer_sums = {k: [] for k in ("food","housing","cost_of_living","health","economic","equity")}
        tiers      = {}
        stall_rates = []
        for d in districts:
            fips = d["fips"]
            ls   = LAYER_SCORES.get(fips, {})
            raw  = ls.get("_raw", {})
            food = d["vulnerability_score"]
            h, c, he, ec = (ls.get("housing",50), ls.get("cost_of_living",50),
                            ls.get("health",50),  ls.get("economic",50))
            eq = round((food+h+c+he+ec)/5)
            for k, v in zip(("food","housing","cost_of_living","health","economic","equity"),
                            (food,h,c,he,ec,eq)):
                layer_sums[k].append(v)
            tiers[d["risk_tier"]] = tiers.get(d["risk_tier"], 0) + 1
            stall_rates.append(raw.get("pipeline_stall_rate", 0) or 0)

        avgs = {k: round(sum(v)/len(v), 1) for k, v in layer_sums.items()}
        worst = max(districts, key=lambda x: x["vulnerability_score"])
        best  = min(districts, key=lambda x: x["vulnerability_score"])

        return {
            "borough":               borough,
            "total_districts":       len(districts),
            "average_layer_scores":  avgs,
            "risk_tier_breakdown":   tiers,
            "most_vulnerable":       {"name": worst["cd_name"],
                                      "score": worst["vulnerability_score"],
                                      "tier": worst["risk_tier"]},
            "least_vulnerable":      {"name": best["cd_name"],
                                      "score": best["vulnerability_score"]},
            "avg_pipeline_stall_pct": round(sum(stall_rates)/len(stall_rates), 1)
                                      if stall_rates else None,
        }

    # ── get_citywide_stats ─────────────────────────────────────────────────────
    elif name == "get_citywide_stats":
        borough_data = {}
        tier_counts  = {}
        layer_extremes = {k: {"high": None, "low": None, "high_score": -1, "low_score": 101}
                          for k in ("food","housing","health","economic","equity")}

        for d in VULN["all"]:
            fips = d["fips"]
            b    = d["borough"]
            ls   = LAYER_SCORES.get(fips, {})
            food = d["vulnerability_score"]
            h, c, he, ec = (ls.get("housing",50), ls.get("cost_of_living",50),
                            ls.get("health",50),  ls.get("economic",50))
            eq = round((food+h+c+he+ec)/5)

            if b not in borough_data:
                borough_data[b] = {k: [] for k in ("food","housing","cost_of_living","health","economic","equity")}
            for k, v in zip(("food","housing","cost_of_living","health","economic","equity"),
                            (food,h,c,he,ec,eq)):
                borough_data[b][k].append(v)

            tier_counts[d["risk_tier"]] = tier_counts.get(d["risk_tier"], 0) + 1

            for k, v in (("food",food),("housing",h),("health",he),
                         ("economic",ec),("equity",eq)):
                if v > layer_extremes[k]["high_score"]:
                    layer_extremes[k]["high"]       = d["cd_name"]
                    layer_extremes[k]["high_score"]  = v
                if v < layer_extremes[k]["low_score"]:
                    layer_extremes[k]["low"]        = d["cd_name"]
                    layer_extremes[k]["low_score"]  = v

        borough_avgs = {
            b: {k: round(sum(v)/len(v), 1) for k, v in layers.items()}
            for b, layers in borough_data.items()
        }
        extremes_clean = {
            k: {"most_stressed":  v["high"], "score": v["high_score"],
                "least_stressed": v["low"],  "low_score": v["low_score"]}
            for k, v in layer_extremes.items()
        }

        return {
            "total_districts":   len(VULN["all"]),
            "risk_tier_breakdown": tier_counts,
            "borough_averages":  borough_avgs,
            "extremes_by_layer": extremes_clean,
            "city_indicator_averages": CITY_AVGS,
        }

    # ── find_housing_pipeline_gaps ─────────────────────────────────────────────
    elif name == "find_housing_pipeline_gaps":
        n       = args.get("n", 5)
        borough = args.get("borough", "").strip().lower()

        results = []
        for d in VULN["all"]:
            if borough and d["borough"].lower() != borough:
                continue
            fips = d["fips"]
            ls   = LAYER_SCORES.get(fips, {})
            raw  = ls.get("_raw", {})
            results.append({
                "name":               d["cd_name"],
                "borough":            d["borough"],
                "housing_score":      ls.get("housing", 50),
                "food_score":         d["vulnerability_score"],
                "risk_tier":          d["risk_tier"],
                "stall_rate_pct":     raw.get("pipeline_stall_rate", 0) or 0,
                "completions_per_1k": raw.get("completions_per1k", 0),
                "pipeline_filed":     raw.get("pipeline_filed", 0),
                "pipeline_permitted": raw.get("pipeline_permitted", 0),
                "pipeline_withdrawn": raw.get("pipeline_withdrawn", 0),
                "pipeline_inactive":  raw.get("pipeline_inactive", 0),
                "hpd_violations_per_1k": raw.get("hpd_per_1k", 0),
                "interpretation": (
                    "critical gap" if (raw.get("pipeline_stall_rate", 0) or 0) > 70
                    else "moderate gap" if (raw.get("pipeline_stall_rate", 0) or 0) > 50
                    else "manageable"
                )
            })

        results.sort(key=lambda x: x["stall_rate_pct"], reverse=True)
        return {
            "borough_filter": borough or "all boroughs",
            "worst_pipeline_gaps": results[:n],
            "note": "stall_rate_pct = (withdrawn+inactive)/(permitted+withdrawn+inactive)*100. Higher = more blocked."
        }

    # ── calculate_allocation ───────────────────────────────────────────────────
    elif name == "calculate_allocation":
        budget  = args.get("budget_dollars", 0)
        layer   = args.get("layer", "equity")
        top_n   = args.get("top_n", 10)
        borough = args.get("borough", "").strip().lower()

        if not budget or budget <= 0:
            return {"error": "budget_dollars must be a positive number"}

        candidates = []
        for d in VULN["all"]:
            if borough and d["borough"].lower() != borough:
                continue
            fips  = d["fips"]
            ls    = LAYER_SCORES.get(fips, {})
            score = _layer_score(fips, layer, ls)
            candidates.append({
                "name":       d["cd_name"],
                "borough":    d["borough"],
                "fips":       fips,
                "risk_tier":  d["risk_tier"],
                "layer_score": score,
                "equity_score": _layer_score(fips, "equity", ls),
            })

        candidates.sort(key=lambda x: x["layer_score"], reverse=True)
        top = candidates[:top_n]

        total_score = sum(c["layer_score"] for c in top)
        allocations = []
        for c in top:
            weight     = c["layer_score"] / total_score if total_score > 0 else 1/len(top)
            alloc      = round(budget * weight)
            per_capita = round(alloc / 140000)  # ~140k avg CD population
            allocations.append({
                "rank":              len(allocations) + 1,
                "name":              c["name"],
                "borough":           c["borough"],
                "risk_tier":         c["risk_tier"],
                f"{layer}_score":    c["layer_score"],
                "equity_score":      c["equity_score"],
                "allocation_dollars": alloc,
                "pct_of_budget":     round(weight * 100, 1),
                "dollars_per_resident": per_capita,
            })

        return {
            "budget":             budget,
            "allocation_layer":   layer,
            "total_districts":    len(allocations),
            "methodology":        f"Proportional weighting by {layer} stress score (0-100)",
            "allocations":        allocations,
            "note": (
                "Allocation is evidence-based but not a policy decision. "
                "Adjust for program-specific eligibility, existing investment, "
                "and agency capacity before finalizing."
            )
        }

